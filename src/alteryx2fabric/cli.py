# ----------------------------- provision -----------------------------
@main.command()
@click.option("--lakehouse", "lakehouse_name", default=None, help="Lakehouse name (defaults to state).")
def provision(lakehouse_name: str | None):
    """Create the Lakehouse in the workspace."""
    client = _get_client_or_exit()
    st = _state.load(_project_root())
    name = lakehouse_name or st.get("lakehouse_name")
    if not name:
        click.secho("lakehouse name not provided", fg="red"); sys.exit(2)
    lh = client.create_lakehouse(name)
    click.secho(f"Lakehouse ready: {lh['displayName']} ({lh['id']})", fg="green")
    _state.update({"lakehouse_id": lh["id"], "lakehouse_name": lh["displayName"]}, _project_root())


# ----------------------------- upload -----------------------------
@main.command()
@click.argument("local_dir")
@click.option("--to", "remote_prefix", default="Input", help="Remote subfolder under Files/.")
def upload(local_dir: str, remote_prefix: str):
    """Upload all files under LOCAL_DIR to OneLake Files/<TO>/."""
    st = _state.load(_project_root())
    ws = st.get("workspace_id")
    lh_name = st.get("lakehouse_name")
    if not (ws and lh_name):
        click.secho("workspace_id / lakehouse_name missing — run init + provision first.", fg="red")
        sys.exit(2)
    ol = OneLake(ws, lh_name)
    src = Path(local_dir)
    n = 0
    for p in sorted(src.iterdir()):
        if p.is_file():
            size = ol.upload(p, f"{remote_prefix}/{p.name}")
            click.echo(f"uploaded {p.name} ({size} bytes)")
            n += 1
    click.secho(f"{n} files uploaded to Files/{remote_prefix}/", fg="green")


# ----------------------------- deploy -----------------------------
@main.command()
@click.option("--inputs-config", default=None, help="JSON file describing bronze inputs.")
@click.option("--prefix", default="Nb", help="Notebook name prefix.")
@click.option("--pipeline-name", default=None, help="Data Pipeline name (default: PL_<project>_Run).")
def deploy(inputs_config: str | None, prefix: str, pipeline_name: str | None):
    """Deploy Bronze/Silver/Gold notebooks and the orchestration pipeline."""
    client = _get_client_or_exit()
    st = _state.load(_project_root())
    lh_id = st.get("lakehouse_id")
    lh_name = st.get("lakehouse_name")
    if not lh_id:
        click.secho("Lakehouse not provisioned. Run `a2f provision` first.", fg="red"); sys.exit(2)

    if inputs_config and Path(inputs_config).exists():
        inputs = json.loads(Path(inputs_config).read_text(encoding="utf-8"))
    else:
        inputs = [{"table": "example", "file": "example.csv"}]
        click.secho("No --inputs-config provided; deploying with a placeholder bronze cell.", fg="yellow")

    nb_ids = deploy_default_notebooks(client, inputs, lh_id, lh_name, prefix=prefix)
    for name, _id in nb_ids.items():
        click.echo(f"  notebook {name}: {_id}")

    pl_name = pipeline_name or f"PL_{st.get('project_name', 'Migration')}_Run"
    chain = [
        ("Bronze Ingest", nb_ids[f"{prefix}_Bronze_Ingest"]),
        ("Silver Transform", nb_ids[f"{prefix}_Silver_Transform"]),
        ("Gold Outputs", nb_ids[f"{prefix}_Gold_Outputs"]),
    ]
    pid = deploy_pipeline(client, pl_name, chain)
    click.secho(f"Pipeline {pl_name}: {pid}", fg="green")
    _state.update({"notebooks": nb_ids, "pipeline_name": pl_name, "pipeline_id": pid}, _project_root())


# ----------------------------- run -----------------------------
@main.command()
@click.option("--pipeline", "pipeline_name", default=None, help="Pipeline name (default: from state).")
@click.option("--timeout", default=1800, help="Timeout in seconds.")
def run(pipeline_name: str | None, timeout: int):
    """Trigger the pipeline and stream status."""
    client = _get_client_or_exit()
    st = _state.load(_project_root())
    pid = st.get("pipeline_id")
    if pipeline_name:
        item = client.find_item(pipeline_name, "DataPipeline")
        if not item:
            click.secho(f"Pipeline '{pipeline_name}' not found.", fg="red"); sys.exit(2)
        pid = item["id"]
    if not pid:
        click.secho("No pipeline id — run `a2f deploy` first or pass --pipeline.", fg="red"); sys.exit(2)

    click.echo(f"Triggering pipeline {pid} ...")
    status_url, progress, final = run_pipeline_and_wait(client, pid, timeout_s=timeout)
    for elapsed, status in progress:
        click.echo(f"  [{elapsed}s] status={status}")
    click.echo("Final:")
    click.echo(json.dumps(final, indent=2)[:1500])
    if final.get("status") != "Completed":
        sys.exit(1)


# ----------------------------- download -----------------------------
@main.command()
@click.argument("remote_path")
@click.option("--out", "out_dir", default="fabric_outputs", help="Local destination dir.")
def download(remote_path: str, out_dir: str):
    """Download a file or all files in a remote folder from OneLake Files/."""
    st = _state.load(_project_root())
    ws = st.get("workspace_id")
    lh_name = st.get("lakehouse_name")
    ol = OneLake(ws, lh_name)
    dest = Path(out_dir); dest.mkdir(parents=True, exist_ok=True)
    # Try as folder first
    try:
        paths = ol.list_dir(remote_path)
        files = [p for p in paths if not p.get("isDirectory")]
        if files:
            for p in files:
                # path looks like Files/<remote_path>/foo.xlsx
                name = p["name"].split("/")[-1]
                full_remote = p["name"].split("Files/", 1)[-1]
                ol.download(full_remote, dest / name)
                click.echo(f"  downloaded {name} ({p.get('contentLength')} bytes)")
            return
    except Exception:
        pass
    # Fall back to single file
    name = remote_path.rsplit("/", 1)[-1]
    ol.download(remote_path, dest / name)
    click.echo(f"  downloaded {name}")


# ----------------------------- validate -----------------------------
@main.command()
@click.option("--ref", "ref_dir", required=True, help="Reference output folder.")
@click.option("--gen", "gen_dir", required=True, help="Generated (Fabric) output folder.")
@click.option("--atol", default=1e-3, help="Numeric tolerance.")
def validate(ref_dir: str, gen_dir: str, atol: float):
    """Diff two folders of result files (xlsx/csv/parquet)."""
    results = diff_folders(ref_dir, gen_dir, atol=atol)
    click.echo(format_report(results))
    if not all(r.passed for r in results):
        sys.exit(1)


# ----------------------------- AI commands -----------------------------
def _llm(provider: str, model: str | None):
    from .ai import LLMClient
    return LLMClient(provider=provider, model=model)


def _load_ir(ir_path: str) -> dict:
    p = Path(ir_path)
    if not p.exists():
        click.secho(f"IR not found at {ir_path}. Run `a2f parse <yxmd> --out ir.json` first.", fg="red")
        sys.exit(2)
    return json.loads(p.read_text(encoding="utf-8"))


@main.group()
@click.option("--provider", type=click.Choice(["github", "anthropic"]), default="github",
              help="LLM provider. github = GitHub Models (uses GITHUB_TOKEN/gh auth).")
@click.option("--model", default=None, help="Model id override (e.g. anthropic/claude-opus-4).")
@click.option("--ir", "ir_path", default="ir.json", help="Path to IR JSON from `a2f parse`.")
@click.pass_context
def generate(ctx, provider, model, ir_path):
    """AI-assisted notebook generation."""
    ctx.ensure_object(dict)
    ctx.obj["llm"] = _llm(provider, model)
    ctx.obj["ir"] = _load_ir(ir_path)


