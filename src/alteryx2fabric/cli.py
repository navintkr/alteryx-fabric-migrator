# ----------------------------- helpers -----------------------------
def _project_root() -> str:
    return os.getcwd()


def _get_client_or_exit() -> FabricClient:
    st = _state.load(_project_root())
    ws = st.get("workspace_id") or os.environ.get("A2F_WORKSPACE_ID")
    if not ws:
        click.secho(
            "Error: workspace_id not set. Run `a2f init <name> --workspace-id <guid>` "
            "or set A2F_WORKSPACE_ID.",
            fg="red",
        )
        sys.exit(2)
    return FabricClient(ws)


# ----------------------------- root group -----------------------------
@click.group()
@click.version_option(__version__, prog_name="a2f")
def main():
    """alteryx2fabric — migrate Alteryx workflows to Microsoft Fabric."""


# ----------------------------- init -----------------------------
@main.command()
@click.argument("name")
@click.option("--workspace-id", required=True, help="Fabric workspace GUID.")
@click.option("--lakehouse-name", default=None, help="Lakehouse display name to use (default: <name>_LH).")
def init(name: str, workspace_id: str, lakehouse_name: str | None):
    """Scaffold a new migration project in ./<NAME>/."""
    root = Path(name)
    if root.exists():
        click.secho(f"Refusing to overwrite existing path: {root}", fg="red")
        sys.exit(2)
    for d in ("inputs", "reference_outputs", "fabric_outputs", "notebooks", ".a2f"):
        (root / d).mkdir(parents=True, exist_ok=True)
    state = {
        "project_name": name,
        "workspace_id": workspace_id,
        "lakehouse_name": lakehouse_name or f"{name}_LH",
    }
    _state.save(state, root)
    (root / "README.md").write_text(
        f"# {name}\n\nGenerated by alteryx2fabric.\n\n"
        "- `inputs/`            — source files to upload to OneLake\n"
        "- `reference_outputs/` — Alteryx-produced files used for validation\n"
        "- `fabric_outputs/`    — files downloaded from Fabric after a run\n"
        "- `notebooks/`         — generated `.ipynb` cache\n"
        "- `.a2f/state.json`    — Fabric IDs for subsequent commands\n",
        encoding="utf-8",
    )
    click.secho(f"Initialised project: {root.resolve()}", fg="green")
    click.echo(f"  workspace_id  = {workspace_id}")
    click.echo(f"  lakehouse     = {state['lakehouse_name']}")


